class TestBuildPathFilter:
    def test_builder_stage_lockfile_is_in_scope_when_copied_from(self, tmp_path):
        (tmp_path / "Dockerfile").write_text(
            "FROM golang:1.22 AS builder\n"
            "COPY go.mod go.sum ./\n"
            "RUN go build\n"
            "FROM ubi9\n"
            "COPY --from=builder /app/binary /usr/bin/binary\n"
        )
        (tmp_path / "go.sum").write_text("github.com/a/b v1.0.0 h1:x=\n")
        scope = build_path_filter(str(tmp_path), find_lockfiles(str(tmp_path)))
        assert scope == {"go.sum"}

    def test_dev_lockfile_outside_build_path_is_excluded(self, tmp_path):
        (tmp_path / "Dockerfile").write_text(
            "FROM python:3.12\n"
            "COPY requirements.txt ./\n"
        )
        (tmp_path / "requirements.txt").write_text("requests==2.31.0\n")
        (tmp_path / "requirements-dev.txt").write_text("pytest==8.0.0\n")
        scope = build_path_filter(str(tmp_path), find_lockfiles(str(tmp_path)))
        assert scope == {"requirements.txt"}

    def test_copy_everything_matches_all(self, tmp_path):
        (tmp_path / "Dockerfile").write_text(
            "FROM ubi9\nCOPY . /app\n"
        )
        (tmp_path / "uv.lock").write_text('[[package]]\nname = "flask"\nversion = "3.0.0"\n')
        scope = build_path_filter(str(tmp_path), find_lockfiles(str(tmp_path)))
        assert scope == {"uv.lock"}

    def test_no_dockerfile_returns_none(self, tmp_path):
        (tmp_path / "go.sum").write_text("github.com/a/b v1.0.0 h1:x=\n")
        assert build_path_filter(str(tmp_path), find_lockfiles(str(tmp_path))) is None

    def test_dockerfile_without_lockfile_references_returns_none(self, tmp_path):
        (tmp_path / "Dockerfile").write_text("FROM ubi9\nRUN dnf install -y something\n")
        (tmp_path / "go.sum").write_text("github.com/a/b v1.0.0 h1:x=\n")
        assert build_path_filter(str(tmp_path), find_lockfiles(str(tmp_path))) is None


