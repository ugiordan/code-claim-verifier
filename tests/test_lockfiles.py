from __future__ import annotations

from code_claim_verifier.lockfiles import (
    LockfileInfo,
    build_path_filter,
    find_lockfiles,
    parse_lockfile,
)
from code_claim_verifier.types import TypedClaim
from code_claim_verifier.verifiers.import_claims import (
    verify_package_absent,
    verify_package_version,
)


def _claim(claim_type: str, parameters: dict) -> TypedClaim:
    return TypedClaim(claim_type=claim_type, parameters=parameters, source_sentence="")


def _info(tmp_path, rel: str, ecosystem: str, kind: str = "lock") -> LockfileInfo:
    return LockfileInfo(path=str(tmp_path / rel), rel=rel, ecosystem=ecosystem, kind=kind)


