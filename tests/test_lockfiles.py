class TestPackageVersion:
    def test_verified_against_build_path_lockfile(self, tmp_path):
        (tmp_path / "Dockerfile").write_text(
            "FROM golang:1.22 AS builder\nCOPY go.mod go.sum ./\n"
            "FROM ubi9\nCOPY --from=builder /app/b /usr/bin/b\n"
        )
        (tmp_path / "go.sum").write_text("github.com/a/b v1.2.3 h1:x=\n")
        result = verify_package_version(
            _claim("PACKAGE_VERSION", {"package": "github.com/a/b", "version": "1.2.3"}),
            str(tmp_path), "go",
        )
        assert result.verdict == "VERIFIED"
        assert result.method_confidence == 0.90

    def test_present_only_outside_build_path_is_refuted(self, tmp_path):
        (tmp_path / "Dockerfile").write_text(
            "FROM python:3.12\nCOPY requirements.txt ./\n"
        )
        (tmp_path / "requirements.txt").write_text("requests==2.31.0\n")
        (tmp_path / "requirements-dev.txt").write_text("pytest==8.0.0\n")
        result = verify_package_version(
            _claim("PACKAGE_VERSION", {"package": "pytest", "version": "8.0.0"}),
            str(tmp_path), "python",
        )
        assert result.verdict == "REFUTED"
        assert "not" in result.evidence and "build path" in result.evidence

    def test_multi_module_go_checked_across_modules(self, tmp_path):
        (tmp_path / "go.sum").write_text("github.com/root/pkg v1.0.0 h1:x=\n")
        sub = tmp_path / "submodule"
        sub.mkdir()
        (sub / "go.mod").write_text("module sub\nrequire github.com/sub/pkg v2.0.0\n")
        result = verify_package_version(
            _claim("PACKAGE_VERSION", {"package": "github.com/sub/pkg", "version": "2.0.0"}),
            str(tmp_path), "go",
        )
        assert result.verdict == "VERIFIED"
        assert "submodule/go.mod" in result.evidence

    def test_not_found_is_unverifiable(self, tmp_path):
        (tmp_path / "requirements.txt").write_text("requests==2.31.0\n")
        result = verify_package_version(
            _claim("PACKAGE_VERSION", {"package": "flask", "version": "3.0.0"}),
            str(tmp_path), "python",
        )
        assert result.verdict == "UNVERIFIABLE"


class TestPackageAbsent:
    def test_absent_everywhere_verifies(self, tmp_path):
        (tmp_path / "go.sum").write_text("github.com/a/b v1.0.0 h1:x=\n")
        result = verify_package_absent(
            _claim("PACKAGE_ABSENT", {"package": "github.com/x/y"}),
            str(tmp_path), "go",
        )
        assert result.verdict == "VERIFIED"
        assert "absent from all" in result.evidence

    def test_present_refutes(self, tmp_path):
        (tmp_path / "go.sum").write_text("github.com/a/b v1.0.0 h1:x=\n")
        result = verify_package_absent(
            _claim("PACKAGE_ABSENT", {"package": "github.com/a/b"}),
            str(tmp_path), "go",
        )
        assert result.verdict == "REFUTED"
        assert "go.sum" in result.evidence

    def test_absent_from_build_path_but_present_in_dev_lockfile_verifies(self, tmp_path):
        (tmp_path / "Dockerfile").write_text(
            "FROM python:3.12\nCOPY requirements.txt ./\n"
        )
        (tmp_path / "requirements.txt").write_text("requests==2.31.0\n")
        (tmp_path / "requirements-dev.txt").write_text("pytest==8.0.0\n")
        result = verify_package_absent(
            _claim("PACKAGE_ABSENT", {"package": "pytest"}),
            str(tmp_path), "python",
        )
        assert result.verdict == "VERIFIED"
        assert "outside the build path" in result.evidence

    def test_no_lockfiles_is_unverifiable(self, tmp_path):
        (tmp_path / "main.py").write_text("print('hi')\n")
        result = verify_package_absent(
            _claim("PACKAGE_ABSENT", {"package": "requests"}),
            str(tmp_path), "python",
        )
        assert result.verdict == "UNVERIFIABLE"

    def test_missing_package_param_is_unverifiable(self, tmp_path):
        result = verify_package_absent(
            _claim("PACKAGE_ABSENT", {}), str(tmp_path), "python",
        )
        assert result.verdict == "UNVERIFIABLE"

    def test_python_package_matching_is_case_insensitive(self, tmp_path):
        (tmp_path / "requirements.txt").write_text("Requests==2.31.0\n")
        result = verify_package_absent(
            _claim("PACKAGE_ABSENT", {"package": "requests"}),
            str(tmp_path), "python",
        )
        assert result.verdict == "REFUTED"
