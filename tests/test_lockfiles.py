class TestDiscovery:
    def test_finds_nested_and_multi_module_lockfiles(self, tmp_path):
        (tmp_path / "go.sum").write_text("github.com/root/pkg v1.0.0 h1:x=\n")
        sub = tmp_path / "submodule"
        sub.mkdir()
        (sub / "go.mod").write_text("module sub\nrequire github.com/sub/pkg v2.0.0\n")
        (tmp_path / "node_modules").mkdir()
        (tmp_path / "node_modules" / "go.mod").write_text("module junk\n")
        (tmp_path / "requirements-prod.txt").write_text("requests==2.31.0\n")

        found = find_lockfiles(str(tmp_path))
        rels = {lf.rel for lf in found}
        assert "go.sum" in rels
        assert "submodule/go.mod" in rels
        assert "requirements-prod.txt" in rels
        assert not any("node_modules" in r for r in rels)


