class TestGoParsers:
    def test_go_sum_resolves_pseudo_versions_to_base(self, tmp_path):
        f = tmp_path / "go.sum"
        f.write_text(
            "github.com/example/pkg v1.2.3 h1:abc=\n"
            "github.com/other/pkg v0.0.0-20260101120000-abcdef123456 h1:def=\n"
        )
        versions = parse_lockfile(_info(tmp_path, "go.sum", "go"))
        assert versions["github.com/example/pkg"] == "1.2.3"
        assert versions["github.com/other/pkg"] == "0.0.0-20260101120000-abcdef123456"

    def test_go_mod_require_blocks_and_inline_comments(self, tmp_path):
        f = tmp_path / "go.mod"
        f.write_text(
            "module example\n"
            "require github.com/a/b v1.0.0 // indirect\n"
            "require (\n"
            "    github.com/c/d v2.1.0\n"
            ")\n"
        )
        versions = parse_lockfile(_info(tmp_path, "go.mod", "go"))
        assert versions == {"github.com/a/b": "1.0.0", "github.com/c/d": "2.1.0"}

    def test_go_mod_replace_overrides_version(self, tmp_path):
        f = tmp_path / "go.mod"
        f.write_text(
            "module example\n"
            "require github.com/a/b v0.1.0\n"
            "replace github.com/a/b => github.com/a/b v1.9.0\n"
        )
        versions = parse_lockfile(_info(tmp_path, "go.mod", "go"))
        assert versions["github.com/a/b"] == "1.9.0"

    def test_go_mod_local_replace_is_not_a_version(self, tmp_path):
        f = tmp_path / "go.mod"
        f.write_text(
            "module example\n"
            "require github.com/a/b v0.1.0\n"
            "replace github.com/a/b => ../local\n"
        )
        versions = parse_lockfile(_info(tmp_path, "go.mod", "go"))
        assert versions["github.com/a/b"] == "0.1.0"

    def test_vendor_modules_txt(self, tmp_path):
        vendor = tmp_path / "vendor"
        vendor.mkdir()
        f = vendor / "modules.txt"
        f.write_text(
            "# github.com/a/b v1.2.3\n"
            "## explicit\n"
            "# github.com/c/d v0.5.0\n"
        )
        versions = parse_lockfile(_info(tmp_path, "vendor/modules.txt", "go"))
        assert versions == {"github.com/a/b": "1.2.3", "github.com/c/d": "0.5.0"}


class TestPythonParsers:
    def test_uv_lock(self, tmp_path):
        f = tmp_path / "uv.lock"
        f.write_text(
            'version = 1\n\n[[package]]\nname = "flask"\nversion = "3.0.0"\n'
            'source = { registry = "https://pypi.org/simple" }\n\n'
            '[[package]]\nname = "requests"\nversion = "2.31.0"\n'
        )
        versions = parse_lockfile(_info(tmp_path, "uv.lock", "python"))
        assert versions == {"flask": "3.0.0", "requests": "2.31.0"}

    def test_requirements_with_markers_and_extras(self, tmp_path):
        f = tmp_path / "requirements.txt"
        f.write_text(
            "# comment\n"
            "requests==2.31.0\n"
            "urllib3[socks]==2.2.1 ; python_version < '3.12'\n"
            "-r other.txt\n"
        )
        versions = parse_lockfile(_info(tmp_path, "requirements.txt", "python"))
        assert versions == {"requests": "2.31.0", "urllib3": "2.2.1"}

    def test_pyproject_exact_pins_only(self, tmp_path):
        f = tmp_path / "pyproject.toml"
        f.write_text(
            "[project]\n"
            'name = "app"\n'
            'dependencies = ["requests==2.31.0", "flask>=2.0"]\n\n'
            "[project.optional-dependencies]\n"
            'dev = ["pytest==8.0.0"]\n'
        )
        versions = parse_lockfile(_info(tmp_path, "pyproject.toml", "python"))
        assert versions == {"requests": "2.31.0", "pytest": "8.0.0"}


class TestOtherParsers:
    def test_cargo_lock(self, tmp_path):
        f = tmp_path / "Cargo.lock"
        f.write_text(
            "# This file is automatically @generated by Cargo.\n"
            "[[package]]\n"
            'name = "serde"\n'
            'version = "1.0.197"\n\n'
            "[[package]]\n"
            'name = "rand"\n'
            'version = "0.8.5"\n'
        )
        versions = parse_lockfile(_info(tmp_path, "Cargo.lock", "rust"))
        assert versions == {"serde": "1.0.197", "rand": "0.8.5"}

    def test_yarn_lock_berry(self, tmp_path):
        f = tmp_path / "yarn.lock"
        f.write_text(
            '__metadata:\n  version: 8\n\n'
            '"lodash@npm:^4.17.0":\n  version: 4.17.21\n'
            '  resolution: "lodash@npm:4.17.21"\n\n'
            '"@scope/util@npm:^1.0.0, @scope/util@npm:^1.2.0":\n  version: 1.5.0\n'
        )
        versions = parse_lockfile(_info(tmp_path, "yarn.lock", "javascript"))
        assert versions == {"lodash": "4.17.21", "@scope/util": "1.5.0"}

    def test_yarn_lock_classic(self, tmp_path):
        f = tmp_path / "yarn.lock"
        f.write_text(
            '# THIS IS AN AUTOGENERATED FILE\n\n'
            'lodash@^4.17.0:\n  version "4.17.21"\n  resolved "https://..."\n\n'
            'chalk@^2.4.1, chalk@^2.4.2:\n  version "2.4.2"\n'
        )
        versions = parse_lockfile(_info(tmp_path, "yarn.lock", "javascript"))
        assert versions == {"lodash": "4.17.21", "chalk": "2.4.2"}

    def test_package_lock_v3(self, tmp_path):
        f = tmp_path / "package-lock.json"
        f.write_text(
            '{"lockfileVersion": 3, "packages": {'
            '"node_modules/express": {"version": "4.18.2"},'
            '"node_modules/@scope/util": {"version": "1.0.0"}'
            "}}"
        )
        versions = parse_lockfile(_info(tmp_path, "package-lock.json", "javascript"))
        assert versions == {"express": "4.18.2", "@scope/util": "1.0.0"}


